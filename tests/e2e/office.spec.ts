test("API: cross-origin mutations rejected; invalid criteria rejected; cancellation recorded", async ({ request }) => {
  const origin = "http://127.0.0.1:3210";
  const cross = await request.post("/api/tasks", { headers: { origin: "https://evil.example" }, data: {} }); expect(cross.status()).toBe(403);
  const config = await (await request.get("/api/config")).json();
  const invalid = await request.post("/api/tasks", { headers: { origin }, data: { ...config.fixture, criteria: [] } }); expect(invalid.status()).toBe(400);
  const response = await request.post("/api/tasks", { headers: { origin }, data: { ...config.fixture, title: "Cancellation API check" } }); expect(response.status()).toBe(201);
  const { task } = await response.json();
  const cancelled = await request.post(`/api/tasks/${task.id}/actions`, { headers: { origin }, data: { action: "cancel" } }); expect(cancelled.ok()).toBe(true);
  const result = await (await request.get(`/api/tasks/${task.id}`)).json(); expect(result.task.status).toBe("cancelled"); expect(result.task.events.some((e: { text: string }) => /cancelled/i.test(e.text))).toBe(true); expect(result.task.baseline).toBeUndefined();
});
